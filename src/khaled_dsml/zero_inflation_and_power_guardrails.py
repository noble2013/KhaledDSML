"""Scientific guardrails for zero inflation, strict nonnested comparison, and
post-study precision. These are deliberately NOT interchangeable tests.

Van den Broek: Biometrics 51 (1995) 738-743, DOI 10.2307/2532959.
Wilson: Economics Letters 127 (2015) 51-53, DOI 10.1016/j.econlet.2014.12.029.
Hoenig and Heisey: The American Statistician 55 (2001) 19-24,
DOI 10.1198/000313001300339897.
"""
from __future__ import annotations

import numpy as np
import pandas as pd
from scipy import stats


def _probability(value, label):
    if (isinstance(value,(bool,np.bool_)) or not np.isscalar(value)
        or not np.isfinite(value) or not 0<value<1):
        raise ValueError(f"{label} must be a finite number strictly in (0,1)")
    return float(value)


def poisson_excess_zero_score(counts, *, alpha=.05):
    """One-sided van den Broek-style excess-zero Poisson score diagnostic.

    For iid intercept-only Poisson counts: lambda_hat=mean(y), p0=exp(-lambda).
    Numerator is observed zeros minus n*p0. The efficient variance is
    n*[p0*(1-p0) - lambda_hat*p0**2], accounting for estimated lambda.
    The directional positive-z p-value uses the large-sample normal tail.
    Also provides the conventional two-sided chi-square(1) reference used
    by the published zero.test implementation. The sign matters:
    negative z is a deficit of zeros, NOT evidence of zero inflation.

    Guard against poor asymptotics with >=5 expected zeros/nonzeros.
    Overdispersion, dependence, covariates or an incorrect Poisson mean
    model can cause apparent excess zeros; this does not establish ZIP.
    """
    alpha=_probability(alpha,"alpha")
    try:
        y=np.asarray(counts,dtype=float)
    except (TypeError,ValueError) as exc:
        raise ValueError("counts must be nonnegative integer observations") from exc
    if (y.ndim!=1 or not 50<=len(y)<=2_000_000
        or not np.isfinite(y).all() or np.any(y<0)
        or not np.array_equal(y,np.floor(y))
        or np.max(y)>1_000_000):
        raise ValueError("Require 50..2,000,000 finite nonnegative integer iid counts")
    n=len(y)
    lam=float(y.mean())
    if lam<=0: raise ValueError("Poisson mean must be positive")
    expected_probability=float(np.exp(-lam))
    expected_zeros=n*expected_probability
    if expected_zeros<5 or n-expected_zeros<5:
        raise ValueError("Expected zero and nonzero counts must each exceed 5")
    variance=float(n*(expected_probability*(1-expected_probability)
                    -lam*expected_probability**2))
    if not np.isfinite(variance) or variance<=1e-12:
        raise ValueError("Degenerate efficient zero-count variance")
    observed_zeros=int(np.count_nonzero(y==0))
    z=float((observed_zeros-expected_zeros)/np.sqrt(variance))
    one_sided=float(stats.norm.sf(z))
    two_sided=float(stats.chi2.sf(z*z,1))
    return {
        "test":"van den Broek excess-zero Poisson score",
        "n_samples":n,"lambda_hat":lam,"n_observed_zeros":observed_zeros,
        "n_expected_zeros":float(expected_zeros),
        "expected_zero_probability":expected_probability,
        "efficient_zero_variance":variance,
        "statistic":z,"chi_square_statistic":float(z*z),
        "p_value":one_sided,"chi_square_two_sided_p_value":two_sided,
        "alpha":alpha,"excess_zero_alarm":bool(z>0 and one_sided<alpha),
        "null_hypothesis_ar":"العدّادات مستقلة وتتبع توزيع بواسون بمعلمة واحدة ولا تتضمن فائض أصفار.",
        "null_hypothesis_en":"Independent counts are generated by an intercept-only Poisson model without excess zeros.",
        "interpretation_ar":(
            "اختبار فان دن بروك لزيادة الأصفار مقارنة ببواسون "
            "مستقل ذي متوسط واحد: يعرض z الموقعة واحتمال الطرف "
            "العلوي وتقدير كاي تربيع ثنائي الطرف. وجود فائض أصفار "
            "لا يثبت ملاءمة ZIP تحديدًا؛ التشتت الزائد أو "
            "الاعتماد أو المتغيرات المفقودة قد تعطي النتيجة نفسها. "
            "ليس اختبار Vuong للنماذج غير المتداخلة."
        ),
        "interpretation_en":(
            "Directional van den Broek Poisson zero-excess score with "
            "estimated-mean variance correction; reports both upper-tail "
            "normal p and the conventional chi-square two-sided p. "
            "It assumes independent identically distributed intercept-only "
            "Poisson counts. Overdispersion, unmodelled heterogeneity or "
            "serial dependence can cause extra zeros. Not a Vuong test "
            "and not proof that ZIP is the correct model."
        ),
    }


def vuong_strictly_nonnested(loglik_model_a, loglik_model_b, *,
                             model_a_family, model_b_family,
                             relationship, alpha=.05):
    """Unadjusted Vuong asymptotic z for genuinely STRICTLY NONNESTED models.

    Both vectors must contain fitted individual log-density contributions
    on exactly the same independent, held-out or appropriately fitted cases.
    Must establish strict nonnestedness and distinguishability independently;
    the declared relationship string is NOT an automatic overlap test.
    The classical z uses sqrt(n)*mean(log fA - log fB)/sample_sd(log fA-log fB)
    and its two-sided standard normal asymptotics. Not valid for nested
    or overlapping Poisson-vs-ZIP comparisons. AIC/BIC corrections and
    model selection search are deliberately NOT provided.
    """
    alpha=_probability(alpha,"alpha")
    if (relationship!="strictly_nonnested"
        or not isinstance(model_a_family,str) or not model_a_family.strip()
        or not isinstance(model_b_family,str) or not model_b_family.strip()
        or model_a_family.casefold().strip()==model_b_family.casefold().strip()):
        raise ValueError("Declare two distinct model families and explicitly establish strictly_nonnested relationship")
    names=[s.lower().replace("-"," ").replace("_"," ").strip()
           for s in (model_a_family,model_b_family)]
    has_zero_inflated=any("zero inflated" in s or "zeroinflated" in s or
                          s=="zip" or s.startswith("zip ") for s in names)
    has_poisson=any("poisson" in s or s=="poisson" for s in names)
    if has_zero_inflated and has_poisson:
        raise ValueError("Poisson and zero-inflated Poisson overlap; classical Vuong is invalid as a zero-inflation test")
    try:
        a=np.asarray(loglik_model_a,dtype=float)
        b=np.asarray(loglik_model_b,dtype=float)
    except (TypeError,ValueError) as exc:
        raise ValueError("Need paired finite individual log likelihood vectors") from exc
    if (a.ndim!=1 or b.ndim!=1 or a.shape!=b.shape
        or not 50<=len(a)<=2_000_000
        or not np.isfinite(a).all() or not np.isfinite(b).all()):
        raise ValueError("Require >=50 paired finite individual log likelihoods")
    diff=a-b
    std=float(np.std(diff,ddof=1))
    if not np.isfinite(std) or std<1e-10:
        raise ValueError("Indistinguishable log-likelihood contributions: asymptotic normal reference undefined")
    z=float(np.sqrt(len(diff))*np.mean(diff)/std)
    p=float(2*stats.norm.sf(abs(z)))
    return {
        "test":"Strictly nonnested Vuong individual-loglikelihood comparison",
        "n_samples":len(diff),"model_a_family":model_a_family,
        "model_b_family":model_b_family,
        "relationship_declared":relationship,
        "mean_loglik_difference_a_minus_b":float(np.mean(diff)),
        "sd_loglik_difference":std,
        "statistic":z,"p_value":p,"alpha":alpha,
        "favored_if_significant":("A" if z>0 else "B") if p<alpha else "inconclusive",
        "interpretation_ar":(
            "اختبار Vuong التقريبي لنموذجين غير متداخلين فعلًا "
            "وبمدخلات احتمالات لوغاريتمية مفردة على الحالات نفسها. "
            "الإعلان عن عدم التداخل يُقدمه الباحث ولا تتحقق منه "
            "الدالة. يُمنع استخدامها لمقارنة بواسون وZIP لأنها "
            "نماذج متداخلة عند الحد، أو لاختبارات بعد اختيار "
            "النموذج من النتائج نفسها."
        ),
        "interpretation_en":(
            "Classical asymptotic Vuong z is for independently validated, "
            "strictly nonnested distinguishable models and matched iid "
            "individual loglikelihood contributions. The caller's "
            "relationship declaration is NOT a model-overlap check. "
            "Poisson versus zero-inflated Poisson is explicitly blocked; "
            "do not use Vuong as a zero-inflation test. Not adjusted "
            "for searching over candidate models."
        ),
    }


def post_study_precision_scenarios(estimate, standard_error,
                                   externally_specified_effects, *, alpha=.05):
    """Post-study CI and transparent *hypothetical* normal power scenarios.

    True-effect scenarios must come from external scientific/design
    considerations, NOT this study's observed estimate or p-value. This
    never returns 'observed/achieved power'. Reuses an estimated study SE
    as a planning approximation; scenario probabilities are functions of
    that SE and hypothetical effects and do not add independent evidence
    to the just-completed analysis. For future design, re-estimate SE
    for the planned sample size and estimator.
    """
    alpha=_probability(alpha,"alpha")
    for value,name in ((estimate,"estimate"),(standard_error,"standard_error")):
        if (isinstance(value,(bool,np.bool_)) or not np.isscalar(value)
            or not np.isfinite(value)):
            raise ValueError(f"{name} must be a finite scalar")
    if standard_error<=0:raise ValueError("standard_error must be positive")
    try: effects=np.asarray(externally_specified_effects,dtype=float)
    except (TypeError,ValueError) as exc:
        raise ValueError("Externally specified true-effect hypotheses must be numeric") from exc
    if (effects.ndim!=1 or not 1<=len(effects)<=50
        or not np.isfinite(effects).all()
        or len(np.unique(effects))!=len(effects)):
        raise ValueError("Require 1..50 distinct finite external true-effect scenarios")
    zcrit=float(stats.norm.ppf(1-alpha/2))
    se=float(standard_error)
    noncentral=effects/se
    scenario_powers=stats.norm.sf(zcrit-noncentral)+stats.norm.cdf(-zcrit-noncentral)
    table=pd.DataFrame({
        "externally_hypothesized_true_effect":effects,
        "hypothetical_normal_power":scenario_powers,
    })
    return {
        "test":"Post-study precision and external-effect sensitivity",
        "estimate":float(estimate),"standard_error":se,
        "ci_lower":float(estimate-zcrit*se),
        "ci_upper":float(estimate+zcrit*se),
        "alpha":alpha,"z_critical":zcrit,
        "n_scenarios":len(effects),
        "observed_power_computed":False,
        "table":table,
        "interpretation_ar":(
            "تعرض دقة التقدير بعد الدراسة بفاصل ثقة تقريبي "
            "وحساسية افتراضية لأحجام أثر مستقلة مفترضة مسبقًا. "
            "لا تحسب القدرة الإحصائية اللاحقة من الأثر المرصود "
            "أو قيمة p؛ إذ تكون هذه القدرة تابعًا للنتيجة "
            "ولا تضيف دليلًا مستقلًا. الأثر الحقيقي المفترض "
            "يأتي من خارج الدراسة، والخطأ المعياري تقريبي."
        ),
        "interpretation_en":(
            "Retrospective normal-approximation precision plus "
            "hypothetical scenario power conditional on EXTERNAL "
            "true-effect values. Does not compute observed/achieved power "
            "from this study's effect estimate or p-value: that quantity "
            "has no independent inferential value. Scenario results "
            "reuse an estimated SE and cannot prove absence of effects."
        ),
    }
